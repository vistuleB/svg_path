"""Generate portable point-location assertions from the pinned extraction."""
import json
import subprocess
from pathlib import Path
root = Path(__file__).resolve().parents[2]
fixtures = json.loads((root/'scripts/paperjs/intersections.json').read_text())
def num(n): return repr(float(n))
def point(p): return 'svg_path.Point('+', '.join(map(num,p))+')'
def path(g):
    curves = ['svg_path.CubicBezier('+', '.join(point(c[i:i+2]) for i in range(0,8,2))+')' for c in g['curves']]
    return 'svg_path.subpath_assert(['+','.join(curves)+'])'+ (' |> svg_path.subpath_assert_close' if g['closed'] else '')+' |> svg_path.subpath_as_path'
s = '''// Generated by scripts/paperjs/generate-intersections.py; do not hand edit.
// Adapted from Paper.js, copyright 2011–2020 Jürg Lehni & Jonathan Puckey.
// MIT license: scripts/paperjs/upstream/LICENSE.txt.
import gleam/float
import gleam/list
import gleeunit/should
import svg_path
import svg_path/intersections

fn check(found: List(svg_path.Point), expected: List(svg_path.Point)) {
  case expected {
    [] -> found |> should.equal([])
    [p, ..rest] -> {
      let assert Ok(remaining) = remove_match(found, p)
      check(remaining, rest)
    }
  }
}

fn remove_match(found: List(svg_path.Point), p: svg_path.Point) {
  case found {
    [] -> Error(Nil)
    [q, ..rest] -> {
      case float.absolute_value(p.x -. q.x) <=. 0.00001
        && float.absolute_value(p.y -. q.y) <=. 0.00001 {
        True -> Ok(rest)
        False -> {
          case remove_match(rest, p) {
            Ok(remaining) -> Ok([q, ..remaining])
            Error(Nil) -> Error(Nil)
          }
        }
      }
    }
  }
}
'''
for i,f in enumerate(fixtures):
    if f['method'] == 'getCrossings': continue
    s+=f'\n// Upstream {f["title"]}, assertion {f["ordinal"]+1}.\npub fn paper_{i:02}_check() {{\nlet left = {path(f["left"])}\n'
    if f['right']:
        s+=f'let right = {path(f["right"])}\nlet assert Ok(found) = intersections.path(left, right)\n'
    else: s+='let assert Ok(found) = intersections.path_self(left)\n'
    s+='check(list.map(found, fn(hit) { hit.point }), ['+','.join(point(e['point']) for e in f['expected'])+'])\n}\n'
support = root/'test/svg_path_paper_intersection_support.gleam'
support.write_text(s)
ledger = json.loads((root/'scripts/paperjs/intersection-status.json').read_text())
assert len(ledger) == len(fixtures)
for i, (entry, fixture) in enumerate(zip(ledger, fixtures)):
    assert entry['id'] == i and entry['upstream'] == fixture['title']
    assert entry['assertion'] == fixture['ordinal'] + 1
def wrappers(ids):
    return 'import svg_path_paper_intersection_support as fixture\n\n' + '\n'.join(
        f'pub fn paper_{i:02}_test() {{ fixture.paper_{i:02}_check() }}' for i in ids) + '\n'
normal = root/'test/svg_path_paper_intersections_test.gleam'
normal.write_text(wrappers(f['id'] for f in ledger if f['status']=='point-locations-pass'))
audit = root/'scripts/paperjs/audit_tests.gleam'
audit.write_text(wrappers(i for i,f in enumerate(fixtures) if f['method']!='getCrossings'))
subprocess.run(['gleam', 'format', str(support), str(normal), str(audit)], check=True)
