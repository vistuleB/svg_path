"""Preserve pinned Paper.js containment assertions as native geometry checks."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
data=json.loads((root/'scripts/paperjs/containment.json').read_text())
fixtures=data['fixtures']; geometries={}
for f in fixtures:
    key=json.dumps(f['geometry'],sort_keys=True)
    if key not in geometries:geometries[key]=len(geometries)
    f['geometry_id']=geometries[key]
def n(x):return repr(float(x))
out=['''// Adapted from pinned Paper.js PathItem_Contains.js; MIT, copyright
// 2011–2020 Jürg Lehni & Jonathan Puckey. See scripts/paperjs/upstream/LICENSE.txt.
// Generated by scripts/paperjs/generate-containment.py.
import gleam/list
import gleeunit/should
import svg_path
import svg_path/containment
''']
for key,id in geometries.items():
    g=json.loads(key);out.append(f'fn geometry_{id}() {{\n  svg_path.path_combine([')
    for p in g['subpaths']:
        if not p['curves']:continue
        out.append('    svg_path.subpath_assert([')
        for c in p['curves']:
            out.append('svg_path.CubicBezier('+','.join(f'svg_path.Point({n(c[i])},{n(c[i+1])})' for i in [0,2,4,6])+'),')
        out.append('])')
        if p['closed']:out.append('|> svg_path.subpath_assert_close')
        out.append('|> svg_path.subpath_as_path,')
    out.append('])\n}\n')
for block in data['blocks']:
    fs=[f for f in fixtures if f['block']==block['block']]
    if not fs:continue
    out.append(f'// {block["title"]}\npub fn paper_containment_block_{block["block"]}_test() {{')
    ids=sorted(set(f['geometry_id'] for f in fs))
    for id in ids:
        group=[f for f in fs if f['geometry_id']==id]
        out.append(f'let path = geometry_{id}()')
        out.append('list.each([')
        for f in group:out.append(f'#({n(f["point"][0])}, {n(f["point"][1])}, {str(f["expected"]).title()}),')
        rule='EvenOdd' if group[0]['geometry']['fillRule']=='evenodd' else 'Nonzero'
        out.append(f'''], fn(sample) {{
          let assert Ok(classification) = containment.path_containment(
            svg_path.Point(sample.0, sample.1), path, svg_path.{rule})
          // Paper includes boundary points in contains().
          {{ classification != svg_path.Outside }} |> should.equal(sample.2)
        }})''')
    out.append('}\n')
(root/'test/svg_path_paper_containment_test.gleam').write_text('\n'.join(out))
print(f'{len(geometries)} distinct geometries, {len(fixtures)} assertions')
