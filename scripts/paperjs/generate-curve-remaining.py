"""Native contract-aware regressions for the remaining applicable Curve blocks."""
import json
from decimal import Decimal
from pathlib import Path
root=Path(__file__).resolve().parents[2];blocks=json.loads((root/'scripts/paperjs/curve-remaining.json').read_text())['blocks']
def n(x):
 s=format(Decimal(repr(float(x))),'f');return s if '.' in s else s+'.0'
def curve(c):return 'svg_path.CubicBezier('+','.join(f'svg_path.Point({n(c[i])},{n(c[i+1])})' for i in [0,2,4,6])+')'
out=['''// Adapted from pinned Paper.js Curve.js; MIT, copyright 2011–2020
// Jürg Lehni & Jonathan Puckey. See scripts/paperjs/upstream/LICENSE.txt.
// Generated by scripts/paperjs/generate-curve-remaining.py.
import gleam/float
import gleam/list
import gleam/option.{Some, None}
import gleeunit/should
import svg_path
import svg_path/containment
import svg_path/distance
import svg_path/measure

fn near(a: Float,b: Float,tolerance: Float) {
  assert float.absolute_value(a -. b) <=. tolerance
}
fn point_near(a: svg_path.Point,b: svg_path.Point,tolerance: Float) {
  near(a.x,b.x,tolerance)
  near(a.y,b.y,tolerance)
}
fn evaluate(c: svg_path.Segment,t: Float) {
  let assert Ok(p) = svg_path.segment_point(c, at: t)
  p
}
fn direction(c: svg_path.Segment,t: Float) {
  let assert Ok(d) = svg_path.segment_directions(c, at: t)
  case d.outgoing, d.incoming {
    Some(p), _ | None, Some(p) -> p
    _, _ -> panic as "Expected a one-sided tangent"
  }
}
''']
def test(name,body):out.append('pub fn '+name+'_test() {\n'+body+'\n}\n')
c=blocks[6]['operations'][0]['curve']
f=[];t=0.0
while t<=1:f.append(t);t+=.1
fractions=','.join(map(n,f))
test('paper_curve_inverse_length_round_trips',f'''let c = {curve(c)}
let assert Ok(length) = measure.segment_length(c)
// Use this library's length; convert Paper's end-relative convention explicitly.
list.each([{fractions}],fn(f) {{
  let forward = length *. f
  let backward = length +. {{ 0.0 -. length *. {{1.0 -. f}} }}
  let assert Ok(t1) = measure.segment_parameter_at_length(c,distance: forward)
  let assert Ok(t2) = measure.segment_parameter_at_length(c,distance: backward)
  near(t1,t2,0.00000001)
  list.each([#(t1,forward),#(t2,backward)],fn(pair) {{
    let assert Ok(part) = svg_path.segment_between(c,from: 0.0,to: pair.0)
    let assert Ok(found) = measure.segment_length(part)
    near(found,pair.1,0.000000002)
  }})
  point_near(direction(c,t1),direction(c,t2),0.00000001)
}})''')
test('paper_curve_length_distance_contract',f'''let c = {curve(c)}
let assert Ok(length) = measure.segment_length(c)
list.each([0.0 -. length, length +. 1.0],fn(value) {{
  let assert Error(svg_path.InvalidLengthDistance(..)) =
    measure.segment_parameter_at_length(c,distance: value)
}})''')
test('paper_curve_location_out_of_range',f'''let c = {curve(c)}
let assert Ok(length) = measure.segment_length(c)
let assert Error(svg_path.InvalidLengthDistance(..)) =
  measure.segment_point_at_length(c,distance: length +. 1.0)''')
ops=[o for o in blocks[13]['operations'] if o['method']=='getTimeOf'];curves={tuple(o['curve']) for o in ops};points=sorted({tuple(o['args'][0]) for o in ops})
# Each projection is checked by distance; a nearest point is not automatically
# proof of membership. Independent rectangle side bounds determine membership.
cases=[]
for o in ops:
 key=(tuple(o['curve']),tuple(o['args'][0]))
 if key not in cases:cases.append(key)
rows=[]
for cv,p in cases:
 inside=min(cv[0],cv[6])<=p[0]<=max(cv[0],cv[6]) and min(cv[1],cv[7])<=p[1]<=max(cv[1],cv[7])
 rows.append(f'#({curve(cv)},svg_path.Point({n(p[0])},{n(p[1])}),{str(inside).title()})')
test('paper_curve_time_of_rectangle_points', '''list.each(['''+','.join(rows)+'''],fn(entry) {
  let assert Ok(projection) = distance.segment_projection(entry.1,to: entry.0)
  point_near(evaluate(entry.0,projection.at),projection.point,0.000000001)
  case entry.2 {
    True -> {
      assert projection.distance <=. 0.000000001
      point_near(projection.point,entry.1,0.000000001)
    }
    False -> { assert projection.distance >. 0.000000001 }
  }
})''')
for i,o in enumerate(blocks[15]['operations']):
 body=f'let c = {curve(o["curve"])}\n'
 body+=f'let assert Ok(t) = measure.segment_parameter_at_length(c,distance: {n(o["args"][0])})\n' if i==0 else f'let t = {n(o["args"][0])}\n'
 expected=blocks[15]['assertions'][i]['expected']
 body+=f'''let assert Ok(#(left,right)) = svg_path.segment_split(c,at: t)
point_near(svg_path.segment_end(left),svg_path.Point({n(expected[0])},{n(expected[1])}),0.000000001)
point_near(svg_path.segment_start(right),svg_path.segment_end(left),0.0)
list.each([0.0,0.25,0.5,0.75,1.0],fn(u) {{
 point_near(evaluate(left,u),evaluate(c,u *. t),0.000000001)
 point_near(evaluate(right,u),evaluate(c,t +. u *. {{1.0 -. t}}),0.000000001)
}})'''
 test('paper_curve_division_'+str(i),body)
for i,o in enumerate(blocks[16]['operations']):
 if not o['args']:continue
 c=o['curve'];d=o['args'][0];ps=[(3*(c[j+2]-c[j]),3*(c[j+3]-c[j+1])) for j in [0,2,4]]
 body='let velocity = svg_path.QuadraticBezier('+','.join(f'svg_path.Point({n(x)},{n(y)})' for x,y in ps)+')\n'
 body+=f'''let direction = svg_path.Point({n(d[0])},{n(d[1])})
let assert Ok(found) = containment.segment_ray_crossings(velocity,origin: svg_path.Point(0.0,0.0),direction: direction)
// Tangency is parallelism, including opposite orientation. These fixtures have
// no zero-speed candidates; verify this before treating roots as tangents.
list.each(found,fn(pair) {{
 let v = evaluate(velocity,pair.0)
 assert v.x *. v.x +. v.y *. v.y >. 0.0
 near(v.x *. direction.y -. v.y *. direction.x,0.0,0.00000001)
}})
'''
 expected=blocks[16]['assertions'][i]['expected']
 if isinstance(expected,list):
  body+='list.length(found) |> should.equal('+str(len(expected))+')\n'
  for value in expected:body+=f'assert list.any(found,fn(pair) {{ float.absolute_value(pair.0 -. {n(value)}) <=. 0.000000001 }})\n'
 else:body+=f'list.length(found) |> should.equal({expected})'
 test('paper_curve_tangent_roots_'+str(i),body)
(root/'test/svg_path_paper_curve_remaining_test.gleam').write_text('\n'.join(out))
print(f'{len(cases)} unique segment/point probes over {len(points)} points and {len(curves)} curves')
