"""Generate diagnostic bounds queries; mismatches do not become passing tests."""
import json
from decimal import Decimal
from pathlib import Path
root=Path(__file__).resolve().parents[2]
fixtures=json.loads((root/'scripts/paperjs/bounds.json').read_text())['fixtures']
def n(x):
 s=format(Decimal(repr(float(x))),'f');return s if '.' in s else s+'.0'
def point(x,y):return f'svg_path.Point({n(x)}, {n(y)})'
def path(f):
 parts=[]
 for p in f['subpaths']:
  if not p['curves']:
   parts.append(f'svg_path.subpath_empty(at: {point(*p["start"])}) |> svg_path.subpath_as_path');continue
  curves=['svg_path.CubicBezier('+', '.join(point(c[i],c[i+1]) for i in [0,2,4,6])+')' for c in p['curves']]
  parts.append('svg_path.subpath_assert(['+','.join(curves)+'])'+(' |> svg_path.subpath_assert_close' if p['closed'] else '')+' |> svg_path.subpath_as_path')
 return 'svg_path.path_combine(['+','.join(parts)+'])'
s=['''// Adapted from pinned Paper.js Item_Bounds.js; MIT license in
// scripts/paperjs/upstream/LICENSE.txt. Generated by generate-bounds.py.
// This is an inventory probe, not a passing regression assertion.
import gleam/io
import gleam/result
import gleam/string
import svg_path
import svg_path/bounds
import svg_path/stroke
import svg_path/offset
import svg_path/transform
pub fn main() {''']
for f in fixtures:s.append(f'io.println("{f["id"]}:" <> string.inspect(fixture_{f["id"]}()))')
s.append('}')
for f in fixtures:
 s.append(f'fn fixture_{f["id"]}() -> Result(List(Float), String) {{\n let path = {path(f)}\n let matrix = transform.matrix('+','.join(n(x) for x in f['matrix'])+')')
 def transform():s.append('use path <- result.try(transform.path(path, by: matrix) |> result.map_error(fn(e) { "transform: " <> string.inspect(e) }))')
 if f['property']=='strokeBounds' and f['stroke']:
  if not f['strokeScaling']:transform()
  join={'miter':f'offset.Miter({n(f["miterLimit"])})','bevel':'offset.Bevel','round':'offset.Round'}[f['join']]
  cap={'butt':'offset.Butt','square':'offset.Square','round':'offset.RoundCap'}[f['cap']]
  width=f['width']/(1 if f['strokeScaling'] else f['zoom'])
  s.append(f'use path <- result.try(stroke.path(path, width: {n(width)}, join: {join}, cap: {cap}) |> result.map_error(fn(e) {{ "stroke: " <> string.inspect(e) }}))')
  if f['strokeScaling']:transform()
 elif f['property']!='internalBounds':transform()
 else:s.append('let _ = matrix')
 s.append('use b <- result.try(bounds.path_bounding_box(path) |> result.map_error(fn(e) { "bounds: " <> string.inspect(e) }))')
 s.append('Ok([{ b.min.x +. b.max.x } /. 2.0, { b.min.y +. b.max.y } /. 2.0])' if f['property']=='position' else 'Ok([b.min.x, b.min.y, b.max.x -. b.min.x, b.max.y -. b.min.y])')
 s.append('}')
(root/'test_paperjs/src/paper_bounds_probe.gleam').write_text('\n'.join(s)+'\n')
